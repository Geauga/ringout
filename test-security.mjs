// test-security.mjs
// Request: Verify PIN protection, revocation and durable rate limits using real SQLite.
import assert from 'node:assert/strict';
import { mkdir, readFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { createVerifier, verifyPin, digest } from './src/auth.mjs';
import { createWorker } from './src/worker.mjs';
import { openDatabase } from './scripts/local-db.mjs';
await mkdir(new URL('.tmp/', import.meta.url), { recursive: true });
const filename = new URL(`.tmp/security-test-${Date.now()}.sqlite`, import.meta.url);
const migrations = new URL('drizzle/', import.meta.url);
let DB = openDatabase(fileURLToPath(filename), migrations);
const pin = '08642179', verifier = await createVerifier(pin);
assert.equal(await verifyPin(pin, verifier), true);
assert.equal(await verifyPin('12345678', verifier), false);
assert.notEqual(verifier, await createVerifier(pin), 'fresh salts');
let now = 180000;
const assets = { '/index.html': { body: '<h1>protected game</h1>', type: 'text/html' }, '/game.js': { body: 'protected code', type: 'text/javascript' } };
const worker = createWorker(assets, () => now);
const env = () => ({ DB, RINGOUT_PIN_HASH: verifier });
const request = (path, { method = 'GET', body, cookie, ip = '192.0.2.1', origin = 'https://game.example' } = {}) => new Request('https://game.example' + path, { method, headers: { origin, 'cf-connecting-ip': ip, ...(cookie ? { cookie } : {}), ...(body !== undefined ? { 'content-type': 'application/x-www-form-urlencoded' } : {}) }, ...(body !== undefined ? { body } : {}) });
const get = (path, cookie) => worker.fetch(request(path, { cookie }), env());
const login = (value = pin, ip = '192.0.2.1') => worker.fetch(request('/unlock', { method: 'POST', body: 'pin=' + value, ip }), env());
assert.equal((await worker.fetch(request('/game.js'), {})).status, 503);
assert.match(await (await get('/')).text(), /8-DIGIT ACCESS PIN/);
for (const path of ['/game.js', '/index.html', '/engine.js', '/server/index.js', '/.env', '/.openai/hosting.json', '/api/session']) assert.equal((await get(path)).status, 401, path);
assert.equal((await login('99999999')).status, 401);
assert.equal((await worker.fetch(request('/unlock', { method: 'POST', body: 'pin=' + pin, origin: 'https://other.example' }), env())).status, 403);
assert.equal((await worker.fetch(request('/unlock', { method: 'POST', body: 'pin=' + '1'.repeat(2000) }), env())).status, 413);
const success = await login();
assert.equal(success.status, 303);
const setCookie = success.headers.get('set-cookie');
for (const flag of ['__Host-ringout=', 'HttpOnly', 'SameSite=Strict', 'Secure', 'Max-Age=28800', 'Path=/']) assert.ok(setCookie.includes(flag), flag);
const cookie = setCookie.split(';')[0];
assert.equal((await get('/game.js', cookie)).status, 200);
assert.equal((await get('/game.js', cookie + '0')).status, 401);
assert.equal((await get('/__proto__', cookie)).status, 404);
const stored = await DB.prepare('SELECT token_hash FROM sessions').bind().first();
assert.equal(stored.token_hash, await digest(cookie.split('=')[1]));
assert.equal((await get('/game.js', cookie)).headers.get('cache-control'), 'no-store');
const newVerifier = await createVerifier('56781234');
assert.equal((await worker.fetch(request('/game.js', { cookie }), { DB, RINGOUT_PIN_HASH: newVerifier })).status, 401, 'PIN rotation revokes sessions');
DB.close(); DB = openDatabase(fileURLToPath(filename), migrations);
assert.equal((await get('/game.js', cookie)).status, 200, 'session survives restart');
assert.equal((await worker.fetch(request('/lock', { method: 'POST', cookie, origin: 'https://other.example' }), env())).status, 403);
assert.equal((await worker.fetch(request('/lock', { method: 'POST', cookie }), env())).status, 303);
assert.equal((await get('/game.js', cookie)).status, 401, 'logout revokes saved cookie');
const expiring = (await login(pin, '192.0.2.2')).headers.get('set-cookie').split(';')[0];
now += 28800;
assert.equal((await get('/game.js', expiring)).status, 401, 'session expires');
for (let i = 0; i < 8; i++) assert.equal((await login('99999999', '192.0.2.3')).status, 401);
DB.close(); DB = openDatabase(fileURLToPath(filename), migrations);
assert.equal((await login(pin, '192.0.2.3')).status, 429, 'rate limit survives restart');
now += 900;
assert.equal((await login(pin, '192.0.2.3')).status, 303, 'rate limit resets');
const concurrent = await Promise.all(Array.from({ length: 12 }, () => login('99999999', '192.0.2.4')));
assert.equal(concurrent.filter(x => x.status === 401).length, 8, 'atomic attempt budget');
assert.equal(concurrent.filter(x => x.status === 429).length, 4);
now += 900;
for (let i = 0; i < 100; i++) assert.equal((await login('bad', `198.51.100.${i}`)).status, 401);
assert.equal((await login(pin, '203.0.113.1')).status, 429, 'global distributed attempt budget');
const { default: bundle } = await import('./dist/server/index.js');
assert.equal((await bundle.fetch(request('/engine.js'), env())).status, 401, 'bundled assets stay protected');
now += 900;
const bundleCookie = (await login()).headers.get('set-cookie').split(';')[0];
// Bundle uses wall time; create a fresh real-time session for its authenticated route.
await DB.prepare('UPDATE sessions SET expires_at = ?').bind(Math.floor(Date.now() / 1000) + 300).run();
assert.match(await (await bundle.fetch(request('/platformer.js', { cookie: bundleCookie }), env())).text(), /PlatformerEngine/);
assert.equal((await bundle.fetch(request('/server/index.js', { cookie: bundleCookie }), env())).status, 404);
assert.equal((await bundle.fetch(request('/.env', { cookie: bundleCookie }), env())).status, 404);
const output = await readFile(new URL('dist/server/index.js', import.meta.url), 'utf8');
assert.ok(!output.includes(verifier) && !output.includes(pin), 'no test secrets embedded');
DB.close();
console.log('Security checks passed: protected assets, PIN verification, CSRF, cookies, expiry, rotation, logout, restart persistence, concurrent/global throttling and built bundle.');
